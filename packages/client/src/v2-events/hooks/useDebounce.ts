import { useEffect, useState } from 'react'

/**
 * Returns a copy of `value` that only updates once `value` has stopped
 * changing for `delay` ms. Each change resets the wait.
 *
 * @param value - the fast-changing value to lag behind
 * @param delay - quiet period in ms before the returned value catches up
 */
export function useDebounce<T>(value: T, delay: number) {
  const [debouncedValue, setDebouncedValue] = useState(value)

  useEffect(() => {
    const handler = setTimeout(() => {
      setDebouncedValue(value)
    }, delay)

    return () => {
      clearTimeout(handler)
    }
  }, [value, delay])

  return debouncedValue
}
